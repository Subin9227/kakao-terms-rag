SELECT_SYSTEM = "당신은 카카오 약관 조항을 고르는 분류기입니다. 번호 하나만 출력합니다."


def build_select_messages(question, evidence, head_chars=220):
    """질문에 직접 답하는 조항 하나를 고르게 한다. 본문은 앞부분만 보여 준다.

    답변 생성 규칙에 "먼저 고르라"를 넣으면 열거가 잘리는 부작용이 있었다. 단계를
    분리하면 고르는 일과 옮겨 적는 일이 서로를 방해하지 않는다.
    """
    lines = []
    for i, (doc, no, title, text) in enumerate(evidence, 1):
        lines.append("{}. {} 제{}조({}) — {}".format(
            i, doc, no, title, text[:head_chars].replace("\n", " ")))
    user = ("[조항 후보]\n{}\n\n[질문]\n{}\n\n"
            "위 질문에 직접 답하는 조항의 번호 하나만 숫자로 출력하세요. 다른 말은 쓰지 마세요."
            ).format("\n".join(lines), question)
    return [{"role": "system", "content": SELECT_SYSTEM}, {"role": "user", "content": user}]


COVER_RULE = (
    "- 위 [반드시 담을 문장]에 적힌 내용은 하나도 빠뜨리지 말고 모두 답변에 담습니다. "
    "질문이 직접 묻지 않은 문장이라도 목록에 있으면 함께 옮깁니다.")


def build_messages(question, evidence, variant="v1", must_sentences=None):
    """evidence: [(doc, article_no, title, text), ...] 관련도 순."""
    blocks = [
        "[{} 제{}조({})]\n{}".format(doc, no, title, text) for doc, no, title, text in evidence
    ]
    if variant == "v2":
        user = "질문:\n{}\n\n제공된 근거 조항:\n{}".format(question, "\n\n".join(blocks))
        return [{"role": "system", "content": SYSTEM_V2}, {"role": "user", "content": user}]
    must = ""
    rules = PROMPTS[variant]
    if must_sentences:
        must = "\n\n[반드시 담을 문장]\n" + "\n".join("- " + s for s in must_sentences)
        rules = rules + "\n" + COVER_RULE
    user = "[근거 조항]\n{}{}\n\n[질문]\n{}\n\n{}".format(
        "\n\n".join(blocks), must, question, rules
    )
    return [{"role": "system", "content": SYSTEM}, {"role": "user", "content": user}]
