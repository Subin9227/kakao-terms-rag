def validate_data(corpus, data):
    assert isinstance(data, dict) and set(data) == {"questions"}, "SCHEMA: root must contain questions"
    questions = data["questions"]
    assert isinstance(questions, list), "SCHEMA: questions must be a list"
    articles = {(row["doc"], row["article_no"]): row for row in corpus}
    assert len(articles) == len(corpus), "CORPUS: duplicate document/article"
    assert questions and len(questions) == len(corpus) * 2, "COUNT: expected exactly two questions per article"

    seen_ids = set()
    seen_questions = set()
    coverage = Counter()
    primary_coverage = Counter()
    for index, item in enumerate(questions, 1):
        assert isinstance(item, dict) and set(item) == QUESTION_FIELDS, f"SCHEMA {index}: fields"
        expected_id = f"S{index:03d}"
        assert item["id"] == expected_id, f"IDS: expected {expected_id}, got {item['id']}"
        assert item["id"] not in seen_ids, f"IDS: duplicate {item['id']}"
        seen_ids.add(item["id"])
        assert item["ptype"] in PTYPES, f"SCHEMA {item['id']}: ptype"
        assert item["difficulty"] in DIFFICULTIES, f"SCHEMA {item['id']}: difficulty"
        assert isinstance(item["question"], str) and item["question"].strip(), f"SCHEMA {item['id']}: question"
        question_key = compact(item["question"])
        assert question_key not in seen_questions, f"DUPLICATE: {item['id']}"
        seen_questions.add(question_key)
        refs = item["gold_articles"]
        assert isinstance(refs, list) and 1 <= len(refs) <= 3, f"SCHEMA {item['id']}: gold_articles"
        if item["ptype"] == "cross":
            assert len(refs) >= 2, f"CROSS: {item['id']} needs at least two gold articles"
        primary_coverage[(refs[0]["doc"], refs[0]["article"])] += 1

        gold_text = []
        for ref in refs:
            assert isinstance(ref, dict) and set(ref) == {"doc", "article", "citation"}, f"SCHEMA {item['id']}: reference"
            key = (ref["doc"], ref["article"])
            assert key in articles, f"GROUNDING {item['id']}: missing article {key}"
            article = articles[key]
            expected_citation = f"{ref['doc']} 제{ref['article']}조({article['title']})"
            assert ref["citation"] == expected_citation, f"SCHEMA {item['id']}: citation"
            coverage[key] += 1
            gold_text.append(article["text"])

        question_text = compact(item["question"])
        article_text = compact("\n".join(gold_text))
        leak_chunks = {question_text[i : i + 10] for i in range(max(0, len(question_text) - 9))}
        leaked = next((chunk for chunk in leak_chunks if chunk and chunk in article_text), None)
        assert leaked is None, f"ANTI-LEAK {item['id']}: {leaked}"

        assert isinstance(item["key_facts"], list) and item["key_facts"], f"GROUNDING {item['id']}: no key facts"
        for fact in item["key_facts"]:
            fact_text = compact(fact)
            assert len(fact_text) >= 12, f"GROUNDING {item['id']}: key fact too short"
            grounded = any(fact_text[i : i + 12] in article_text for i in range(len(fact_text) - 11))
            assert grounded, f"GROUNDING {item['id']}: {fact}"

    expected_coverage = set(articles)
    missing = sorted(key for key in expected_coverage if coverage[key] < 2)
    assert not missing, f"COVERAGE: articles below two questions: {missing}"
    wrong_primary = sorted((key, count) for key, count in primary_coverage.items() if count != 2)
    assert set(primary_coverage) == expected_coverage and not wrong_primary, f"COUNT: primary questions per article {wrong_primary}"
    assert len(seen_ids) == len(questions), "IDS: duplicate ids"
    return {"total": len(questions), "ptype": Counter(q["ptype"] for q in questions), "difficulty": Counter(q["difficulty"] for q in questions)}


def build_data(corpus):
    expected = {(row["doc"], row["article_no"]): row for row in corpus}
    assert len(SPECS) == len(corpus) * 2, "SPECS: expected two authored questions per article"
    owners = Counter(spec["owner"] for spec in SPECS)
    assert set(owners) == set(expected) and all(count == 2 for count in owners.values()), "SPECS: ownership"
    questions = []
    for index, spec in enumerate(SPECS, 1):
        refs = []
        for doc, article_no in spec["gold"]:
            row = expected[(doc, article_no)]
            refs.append({
                "doc": doc,
                "article": article_no,
                "citation": f"{doc} 제{article_no}조({row['title']})",
            })
        questions.append({
            "id": f"S{index:03d}",
            "question": spec["question"],
            "ptype": spec["ptype"],
            "difficulty": spec["difficulty"],
            "gold_articles": refs,
            "key_facts": spec["key_facts"],
        })
    return {"questions": questions}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="validate the existing JSON")
    args = parser.parse_args()
    with CORPUS_PATH.open(encoding="utf-8") as source:
        corpus = json.load(source)
    if args.check:
        with BENCH_PATH.open(encoding="utf-8") as source:
            data = json.load(source)
    else:
        data = build_data(corpus)
        with BENCH_PATH.open("w", encoding="utf-8") as target:
            json.dump(data, target, ensure_ascii=False, indent=2)
            target.write("\n")
    stats = validate_data(corpus, data)
    print(f"total questions: {stats['total']}")
    print("count per ptype: " + ", ".join(f"{key}={stats['ptype'][key]}" for key in sorted(PTYPES)))
    print("count per difficulty: " + ", ".join(f"{key}={stats['difficulty'][key]}" for key in sorted(DIFFICULTIES)))
    print("all five constraints pass")


if __name__ == "__main__":
    main()
